//! The TypeScript prerequisite, decided once for `cho index` and the viewer: a project whose
//! `package.json` declares dependencies needs an installed `node_modules`, in its own folder
//! or hoisted to the repository root. Chorong never installs packages itself.

use crate::indexer::{Language, Project};
use std::path::Path;

/// What a TypeScript project has of `node_modules`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NodeModules {
    /// Installed in the project's folder or at the repository root (a hoisted workspace),
    /// or the project is not TypeScript.
    Installed,
    /// Missing, and the project (or the repository root) declares dependencies: package
    /// types won't resolve until they are installed. `at` is the project folder
    /// (repository-relative, `.` for the root).
    Missing { at: String },
    /// Missing, but nothing declares dependencies: it builds as it is.
    NotNeeded { at: String },
}

/// Checks `project` (in the repository at `repo_root`).
pub fn check(project: &Project, repo_root: &Path) -> NodeModules {
    if project.language != Language::TypeScript
        || project.root.join("node_modules").is_dir()
        || repo_root.join("node_modules").is_dir()
    {
        return NodeModules::Installed;
    }
    let at = if project.rel.is_empty() {
        ".".to_string()
    } else {
        project.rel.clone()
    };
    if declares_dependencies(&project.root.join("package.json"))
        || declares_dependencies(&repo_root.join("package.json"))
    {
        NodeModules::Missing { at }
    } else {
        NodeModules::NotNeeded { at }
    }
}

/// Does `package.json` declare any dependencies?
fn declares_dependencies(package_json: &Path) -> bool {
    let Ok(bytes) = cho_core::fs::read_source(package_json) else {
        return false;
    };
    let Ok(v) = serde_json::from_slice::<serde_json::Value>(&bytes) else {
        return false;
    };
    ["dependencies", "devDependencies", "peerDependencies"]
        .iter()
        .any(|k| {
            v.get(k)
                .and_then(|d| d.as_object())
                .is_some_and(|d| !d.is_empty())
        })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    #[allow(clippy::disallowed_methods)] // the test writes its own files
    fn installed_hoisted_missing_or_not_needed() {
        let dir = std::env::temp_dir().join(format!("cho-nm-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let web = dir.join("web");
        std::fs::create_dir_all(&web).unwrap();
        let p = Project {
            language: Language::TypeScript,
            root: web.clone(),
            rel: "web".into(),
        };
        let at = || "web".to_string();
        // No dependencies declared: builds as it is.
        std::fs::write(web.join("package.json"), "{}").unwrap();
        assert_eq!(check(&p, &dir), NodeModules::NotNeeded { at: at() });
        // Declared at the repository root (a workspace) or in the project: missing.
        std::fs::write(dir.join("package.json"), r#"{"devDependencies":{"x":"1"}}"#).unwrap();
        assert_eq!(check(&p, &dir), NodeModules::Missing { at: at() });
        // Hoisted to the repository root, or in the project's folder: installed.
        std::fs::create_dir(dir.join("node_modules")).unwrap();
        assert_eq!(check(&p, &dir), NodeModules::Installed);
        std::fs::remove_dir(dir.join("node_modules")).unwrap();
        std::fs::create_dir(web.join("node_modules")).unwrap();
        assert_eq!(check(&p, &dir), NodeModules::Installed);
        let _ = std::fs::remove_dir_all(&dir);
    }
}
